import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const manifest=JSON.parse(read('manifest.json'));
assert.match(manifest.id,/^[a-z][a-z0-9-]*$/);
assert.equal(manifest.id,'month-planner');
assert.match(manifest.name,/^[A-Za-z0-9 +()-]+$/);
assert.match(manifest.version,/^\d+\.\d+\.\d+$/);
assert.equal(JSON.parse(read('package.json')).version,manifest.version);
assert.equal(JSON.parse(read('versions.json'))[manifest.version],manifest.minAppVersion);
assert.equal(manifest.isDesktopOnly,false);
assert.ok(manifest.author.trim());
assert.ok(manifest.description.length<=250&&manifest.description.endsWith('.'));
for(const name of ['README.md','LICENSE','src/plugin.js','src/calendar.js','src/ui-template.html'])assert.ok(read(name).length>0);
assert.ok(read('LICENSE').startsWith('MIT License'));
const main=read('main.js');
new vm.Script(main,{filename:'main.js'});
assert.ok(!main.includes('__MONTH_PLANNER_HTML__'),'Unresolved interface marker');
assert.ok(!main.includes("require('./calendar.js')"),'Unbundled calendar import');
assert.ok(!main.includes("adapter.read(this.plugin.manifest.dir+'/ui.html')"),'External interface dependency');
assert.ok(main.includes('MONTH_PLANNER_BOOTSTRAP'),'Missing embedded host bootstrap');
assert.ok(!main.includes('file:///')&&!main.includes('\\\\Users\\\\'),'Local filesystem information in runtime');
const preview=read('ui.html');
assert.ok(!preview.includes('localStorage.'),'Browser storage was not replaced');
assert.ok(!preview.includes('阅读 ViT')&&!preview.includes('完成 VGG'),'Demo task found in release');
const inline=[...preview.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(inline.length,1);
new vm.Script(inline[0][1],{filename:'embedded-interface.js'});
assert.ok(!/<(?:script|link|img|iframe)\b[^>]*(?:src|href)=["']https?:/i.test(preview),'Network asset in offline UI');
const files=['main.js','manifest.json','styles.css'].map(file=>({file,bytes:fs.statSync(path.join(root,file)).size,sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex')}));
console.log(JSON.stringify({version:manifest.version,standardReleaseFiles:files,staticChecksPassed:true,iosHardwareTested:false},null,2));
